import assert from "node:assert/strict"
import { test } from "node:test"

import { getOpeningHoursStatus } from "./get-opening-hours-status"
import { roomOpeningHours } from "./room-opening-hours"

const cases: [number, string, string][] = [
	[1, "2026-09-07T10:59:00", "Закрыто до 11:00"],
	[1, "2026-09-07T11:00:00", "Открыто до 12:20"],
	[1, "2026-09-07T12:20:00", "Закрыто до 13:00"],
	[1, "2026-09-07T13:00:00", "Открыто до 17:00"],
	[1, "2026-09-08T12:00:00", "Закрыто до 13:00"],
	[1, "2026-09-11T17:00:00", "Закрыто до понедельника, 11:00"],
	[12, "2026-09-07T14:29:00", "Открыто до 14:30"],
	[12, "2026-09-07T14:30:00", "Закрыто до 15:00"],
	[12, "2026-09-07T15:00:00", "Открыто до 20:00"],
	[12, "2026-09-05T14:45:00", "Открыто до 15:00"],
	[12, "2026-09-05T15:00:00", "Закрыто до воскресенья, 9:00"],
	[21, "2026-09-04T09:00:00", "Открыто до 16:00"],
	[21, "2026-09-04T16:00:00", "Закрыто до понедельника, 9:00"],
	[21, "2026-09-06T23:59:00", "Закрыто до понедельника, 9:00"],
	[21, "2026-09-07T00:00:00", "Закрыто до 9:00"],
	[70, "2026-09-04T13:45:00", "Закрыто до 14:15"],
	[70, "2026-09-04T14:15:00", "Открыто до 15:30"],
	[70, "2026-09-04T15:30:00", "Закрыто до понедельника, 9:00"],
	[70, "2026-09-07T15:30:00", "Закрыто до вторника, 9:00"],
]

for (const [roomId, localTime, expected] of cases) {
	test(`room ${roomId} at ${localTime}: ${expected}`, () => {
		const hours = roomOpeningHours[roomId]
		assert.ok(hours)
		assert.equal(getOpeningHoursStatus(hours, new Date(localTime)), expected)
	})
}
